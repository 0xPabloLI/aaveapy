#!/usr/bin/env node
/**
 * Build-time: scans public/icons/networks/ and generates a manifest of
 * (baseName -> [extensions]) so the app only uses paths that exist.
 * Chain keys in chainIconMap may be synced before assets land; runtime
 * resolves icons only when a file is present.
 *
 * Usage: node scripts/generate-chain-icon-manifest.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const NETWORKS_DIR = path.join(ROOT, 'public', 'icons', 'networks');
const OUT_PATH = path.join(ROOT, 'src', 'lib', 'chainIconManifest.generated.ts');

const PREFERRED_ORDER = ['svg', 'webp', 'png', 'jpg', 'jpeg'];

function collectManifest() {
  if (!fs.existsSync(NETWORKS_DIR)) {
    return {};
  }

  const files = fs.readdirSync(NETWORKS_DIR, { withFileTypes: true });
  const byBase = new Map();

  for (const ent of files) {
    if (!ent.isFile()) continue;
    const name = ent.name;
    const ext = path.extname(name).slice(1).toLowerCase();
    if (!ext) continue;
    const base = path.basename(name, path.extname(name)).toLowerCase();
    if (!byBase.has(base)) byBase.set(base, []);
    const arr = byBase.get(base);
    if (!arr.includes(ext)) arr.push(ext);
  }

  const manifest = {};
  for (const [base, exts] of byBase) {
    exts.sort((a, b) => PREFERRED_ORDER.indexOf(a) - PREFERRED_ORDER.indexOf(b));
    manifest[base] = exts;
  }

  return manifest;
}

function generateTs(manifest) {
  const entries = Object.entries(manifest)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([key, exts]) =>
        `  "${key.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}": [${exts.map((e) => `"${e}"`).join(', ')}]`
    );
  return `/** Generated by scripts/generate-chain-icon-manifest.mjs - do not edit manually */
export const CHAIN_ICON_MANIFEST: Record<string, readonly string[]> = {
${entries.join(',\n')}
};
`;
}

const manifest = collectManifest();
const ts = generateTs(manifest);
fs.writeFileSync(OUT_PATH, ts, 'utf8');
console.log(
  `[generate-chain-icon-manifest] Wrote ${Object.keys(manifest).length} bases to ${path.relative(ROOT, OUT_PATH)}`
);
