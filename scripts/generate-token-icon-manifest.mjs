#!/usr/bin/env node
/**
 * Build-time script: scans public/icons/tokens/ and generates a manifest of
 * (symbol -> [extensions]) so the app only requests icon paths that exist.
 * Reduces 404s on deploy (e.g. Vercel) where we'd otherwise try svg/webp/png
 * for every symbol.
 *
 * Usage: node scripts/generate-token-icon-manifest.mjs
 * Run before `vite build` (see package.json "build" script).
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import { writeGeneratedFileIfChanged } from './lib/write-generated-file-if-changed.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const TOKENS_DIR = path.join(ROOT, 'public', 'icons', 'tokens');
const OUT_PATH = path.join(ROOT, 'src', 'lib', 'tokenIconManifest.generated.ts');

const PREFERRED_ORDER = ['svg', 'webp', 'png', 'jpg', 'jpeg'];

function collectManifest() {
  if (!fs.existsSync(TOKENS_DIR)) {
    return {};
  }

  const files = fs.readdirSync(TOKENS_DIR, { withFileTypes: true });
  const byBase = new Map();

  for (const ent of files) {
    if (!ent.isFile()) continue;
    const name = ent.name;
    const ext = path.extname(name).slice(1).toLowerCase();
    if (!ext) continue;
    const base = path.basename(name, path.extname(name)).toLowerCase();
    if (!byBase.has(base)) byBase.set(base, []);
    const arr = byBase.get(base);
    if (!arr.includes(ext)) arr.push(ext);
  }

  const manifest = {};
  for (const [base, exts] of byBase) {
    exts.sort((a, b) => PREFERRED_ORDER.indexOf(a) - PREFERRED_ORDER.indexOf(b));
    manifest[base] = exts;
  }

  return manifest;
}

function generateTs(manifest) {
  const entries = Object.entries(manifest)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, exts]) => `  "${key.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}": [${exts.map((e) => `"${e}"`).join(', ')}]`);
  return `/** Generated by scripts/generate-token-icon-manifest.mjs - do not edit manually */
export const TOKEN_ICON_MANIFEST: Record<string, readonly string[]> = {
${entries.join(',\n')}
};
`;
}

const manifest = collectManifest();
const ts = generateTs(manifest);
if (writeGeneratedFileIfChanged(OUT_PATH, ts)) {
  console.log(`[generate-token-icon-manifest] Wrote ${Object.keys(manifest).length} symbols to ${path.relative(ROOT, OUT_PATH)}`);
}
