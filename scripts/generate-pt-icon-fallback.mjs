#!/usr/bin/env node
/**
 * Extracts PT token icon fallback mappings from reservePatches.ts.
 *
 * The upstream fetchIconSymbolAndName() function contains explicit if-statements
 * mapping PT symbols (e.g. pt-susde-28may2026) to iconSymbol values
 * (e.g. ptsusde). This script extracts those mappings so preloadUtils.ts
 * can use the upstream convention for its first-layer PT icon fallback.
 *
 * Usage: node scripts/generate-pt-icon-fallback.mjs
 * Run before `vite build` (see run-icon-manifest-generators.mjs).
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import { writeGeneratedFileIfChanged } from './lib/write-generated-file-if-changed.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const RESERVE_PATCHES_PATH = path.join(ROOT, 'src', 'ui-config', 'reservePatches.ts');
const OUT_PATH = path.join(ROOT, 'src', 'lib', 'ptIconFallback.generated.ts');

function extractPtMappings(content) {
  // Match patterns like:
  //   if (lowerSymbol.startsWith('pt-susde-') || lowerSymbol.startsWith('pt susde')) {
  //     return { symbol, iconSymbol: 'ptsusde', name: name ?? symbol, logoURI };
  //   }
  const regex = /if\s*\(\s*lowerSymbol\.startsWith\('pt-(\w+)-'\)[\s\S]*?\n\s*return\s*\{[^}]*iconSymbol:\s*'([^']+)'/g;

  const mappings = new Map();
  let match;
  while ((match = regex.exec(content)) !== null) {
    const base = match[1].toLowerCase();
    const iconSymbol = match[2].toLowerCase();
    if (!mappings.has(base)) {
      mappings.set(base, iconSymbol);
    }
  }
  return mappings;
}

function generateTs(mappings) {
  if (mappings.size === 0) {
    return `/** Generated by scripts/generate-pt-icon-fallback.mjs - do not edit manually */
/** Upstream PT token icon fallback mappings extracted from reservePatches.ts */
export const PT_ICON_FALLBACK_MAP: Record<string, string> = {};
`;
  }

  const entries = Array.from(mappings.entries())
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([base, iconSymbol]) => `  "${base}": "${iconSymbol}"`);

  return `/** Generated by scripts/generate-pt-icon-fallback.mjs - do not edit manually */
/** Upstream PT token icon fallback mappings extracted from reservePatches.ts */
export const PT_ICON_FALLBACK_MAP: Record<string, string> = {
${entries.join(',\n')}
};
`;
}

function main() {
  const content = fs.readFileSync(RESERVE_PATCHES_PATH, 'utf8');
  const mappings = extractPtMappings(content);
  const ts = generateTs(mappings);

  if (writeGeneratedFileIfChanged(OUT_PATH, ts)) {
    console.log(`[generate-pt-icon-fallback] Extracted ${mappings.size} PT mapping(s) from reservePatches.ts`);
    for (const [base, iconSymbol] of mappings) {
      console.log(`  pt-${base}-* → ${iconSymbol}`);
    }
  } else {
    console.log(`[generate-pt-icon-fallback] No changes (${mappings.size} mapping(s))`);
  }
}

main();
